import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { z } from 'zod';
import { schemas } from '../../packages/contracts/src/schemas.ts';
import { tables, payloadSchemaVersion } from '../../packages/data-schema/src/replication/public.ts';
import { canonical, digest } from '../../packages/kernel/src/public.ts';
import { operations } from '../../packages/contracts/src/operations.ts';

const root = resolve(import.meta.dirname, '../..');
const checking = process.argv.includes('--check');
const generated: Record<string, string> = {};
function javaType(property: Record<string, unknown>): string {
  if (property['type'] === 'string') return 'String';
  if (property['type'] === 'boolean') return 'Boolean';
  if (property['type'] === 'array') return 'java.util.List<com.fasterxml.jackson.databind.JsonNode>';
  return 'com.fasterxml.jackson.databind.JsonNode';
}
const records: string[] = [];
const definitions: Record<string, unknown> = {};
for (const [name, schema] of Object.entries(schemas)) {
  const json = z.toJSONSchema(schema, { target: 'draft-2020-12', io: 'input', reused: 'inline' });
  definitions[name] = json;
  generated['contracts/schema/' + name + '.json'] = JSON.stringify(json, null, 2) + '\n';
  const properties = json.properties as Record<string, Record<string, unknown>>;
  records.push('  public record ' + name + '(' + Object.entries(properties).map(([field, property]) => javaType(property) + ' ' + field).join(', ') + ') {}');
}
generated['contracts/schema/replication.json'] = JSON.stringify({ payloadSchemaVersion, tables, canonical: 'evoloop-canonical-v1', numericRepresentation: 'decimal-strings' }, null, 2) + '\n';
generated['contracts/schema/index.json'] = JSON.stringify({ schemas: Object.keys(schemas) }, null, 2) + '\n';
generated['contracts/java/Wire.java'] = '// Generated by tooling/generators/contracts.ts. Do not edit.\npackage com.evoloop.cloud.generated;\n\npublic final class Wire {\n  private Wire() {}\n' + records.join('\n') + '\n}\n';
const golden = [
  { name: 'precision-unicode', value: { z: null, big: '9223372036854775807', decimal: '900719925474099312345.125', day: '2026-10-17', instant: '2026-10-16T16:00:00.000Z', text: '中文😀', array: ['b', 'a'], tombstone: true } },
  { name: 'key-order', value: { '😀': 'emoji', '\ue000': 'private', a: '\n\t\r"\\', empty: {} } },
];
generated['contracts/examples/canonical-v1.json'] = JSON.stringify(golden.map(sample => ({ ...sample, canonical: canonical(sample.value), digest: digest(sample.value) })), null, 2) + '\n';
const paths: Record<string, unknown> = {};
for (const operation of operations) {
  const path = '/api/v2' + operation.path;
  const value: Record<string, unknown> = { description: operation.description,
    security: operation.path === '/identity/accounts' || operation.path === '/identity/sessions/password' ? [] : [{ bearer: [] }],
    responses: { [operation.status]: { description: operation.description, ...('response' in operation ? { content: { 'application/json': { schema: { $ref: '#/components/schemas/' + operation.response } } } } : {}) },
      '400': { description: 'PAYLOAD_INVALID' }, '401': { description: 'SESSION_REQUIRED / SESSION_EXPIRED' }, '403': { description: 'PURPOSE_REQUIRED / OWNER_MISMATCH' },
      '409': { description: 'Version, immutable ID or recovery conflict' }, '422': { description: 'Protocol validation or digest failure' }, '429': { description: 'RATE_LIMITED' }, '503': { description: 'Dependency unavailable; no mock fallback' } },
  };
  if ('request' in operation) value['requestBody'] = { required: true, content: { 'application/json': { schema: { $ref: '#/components/schemas/' + operation.request } } } };
  const parameters: unknown[] = [];
  if (operation.path.includes('{id}')) parameters.push({ name: 'id', in: 'path', required: true, schema: { type: 'string', format: 'uuid' } });
  if (operation.path === '/sync/batches' && operation.method === 'get') parameters.push({ name: 'afterSequence', in: 'query', schema: { type: 'string', pattern: '^(0|[1-9]\\d*)$', default: '0' } });
  if (operation.path === '/ai/tasks/{id}' && operation.method === 'delete') parameters.push({ name: 'expectedVersion', in: 'query', required: true, schema: { type: 'string', pattern: '^[1-9]\\d*$' } });
  if (parameters.length) value['parameters'] = parameters;
  paths[path] = { ...(paths[path] as object ?? {}), [operation.method]: value };
}
generated['contracts/openapi/evoloop-v2.json'] = JSON.stringify({ openapi: '3.1.0', info: { title: 'EvoLoop Java cloud', version: '0.1.0' }, paths,
  components: { schemas: definitions, securitySchemes: { bearer: { type: 'http', scheme: 'bearer' } } } }, null, 2) + '\n';
for (const [path, content] of Object.entries(generated)) {
  const destination = resolve(root, path);
  if (checking) {
    if (await readFile(destination, 'utf8').catch(() => '') !== content) throw new Error('Generated output differs: ' + path);
  } else {
    await mkdir(dirname(destination), { recursive: true });
    await writeFile(destination, content, 'utf8');
  }
}
process.stdout.write((checking ? 'Verified ' : 'Generated ') + Object.keys(generated).length + ' protocol artifacts\n');
